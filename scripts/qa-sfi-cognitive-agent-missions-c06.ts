import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { SFI_CONVERGED_COGNITIVE_AGENT_REGISTRY } from '../src/lib/sfi/cognitive-runtime/convergedRegistry';
import { SFI_AGENT_EXECUTION_MAP } from '../src/lib/sfi/cognitive-runtime/agentExecutionMap';
import { executionContractForAgent } from '../src/lib/sfi/cognitive-runtime/executionContracts';
import { listBoundedCognitiveMissions, SFI_COGNITIVE_MISSION_CONTRACT } from '../src/lib/sfi/cognitive-runtime/missionCatalog';

const missions=listBoundedCognitiveMissions();
const registeredIds=SFI_CONVERGED_COGNITIVE_AGENT_REGISTRY.map(agent=>agent.id);
assert.equal(registeredIds.length,21,'C06 must bind the EXISTING 21-agent cognitive registry');
assert.equal(missions.length,registeredIds.length,'one bounded mission per existing agent');
assert.deepEqual(missions.map(m=>m.agentId),registeredIds,'mission order must derive from canonical registry');
assert.equal(new Set(missions.map(m=>m.agentId)).size,21);
assert.equal(new Set(missions.map(m=>m.missionId)).size,21);
assert.equal(new Set(missions.map(m=>m.title)).size,21,'missions must be genuinely distinct');
for(const mission of missions){
  const agent=SFI_CONVERGED_COGNITIVE_AGENT_REGISTRY.find(a=>a.id===mission.agentId)!;
  const contract=executionContractForAgent(mission.agentId);
  assert.ok(contract,`missing real execution contract for ${mission.agentId}`);
  assert.equal(mission.contract,SFI_COGNITIVE_MISSION_CONTRACT);
  assert.equal(mission.missionId,'SFI-C06:'+agent.id);
  assert.equal(mission.agentName,agent.name);
  assert.equal(mission.triggerRegistered,true);
  assert.ok(agent.listensTo.includes(mission.trigger),`trigger not on agent passport: ${agent.id}`);
  assert.ok(mission.emits.every(event=>agent.emits.some(raw=>typeof raw==='string'?raw===event:raw.eventName===event)),`emits must match canonical passport events: ${agent.id}`);
  assert.deepEqual(mission.sourceTables,agent.sourceTables);
  assert.equal(typeof SFI_AGENT_EXECUTION_MAP[agent.id],'function',`no canonical executor: ${agent.id}`);
  assert.ok(mission.inputKinds.length>0,`no target kinds for ${agent.id}`);
  assert.ok(mission.inputKinds.every(kind=>contract.allowedTargetKinds.includes(kind)),
    `mission target exceeds canonical contract: ${agent.id}`);
  assert.equal(mission.minimumTargets,contract.minTargets);
  assert.equal(mission.maximumTargets,contract.maxTargets);
  assert.equal(mission.executionContractVersion,contract.version);
  assert.equal(mission.humanApprovalRequired,agent.humanApprovalRequired);
  assert.equal(mission.authorityLevel,agent.authorityLevel);
  assert.equal(mission.simulationAllowed,agent.simulationAllowed);
  for(const field of ['objective','prerequisite','deliverable','forbiddenPromotion','title'] as const){
    assert.ok(mission[field].trim().length>20,`${agent.id} must declare a concrete ${field}`);
  }
  assert.equal(mission.assignmentState,'TEMPLATE_DEFINED_NOT_QUEUED');
  assert.equal(mission.executionObservation,'NOT_EXECUTED_BY_MISSION_CATALOG');
  assert.equal(mission.dispatchState,'ROOT_MANUAL_ONLY_C07');
  assert.equal(mission.scheduleState,'NOT_CONNECTED_UNTIL_C08');
  assert.equal(mission.targetBindingState,'REQUIRES_AUTHORIZED_EXISTING_OBJECT');
  assert.equal(mission.costState,'NOT_REQUESTED_NOT_SPENT');
  assert.equal(mission.permissionDelta,0,'no agent may acquire new authority from C06');
}
